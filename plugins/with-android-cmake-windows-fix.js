/**
 * Backport of Expo SDK 57's android.cmakeVersion / CMAKE_OBJECT_PATH_MAX
 * handling. AGP defaults to CMake 3.22.1, and react-native-worklets /
 * reanimated pin that version, whose Ninja 1.10 fails on Windows long paths
 * (`mkdir(...CMakeFiles/worklets.dir/C_/Users/...): No such file or directory`
 * and `build.ninja still dirty after 100 tries`).
 *
 * Requires CMake 3.31.6 in the Android SDK (Ninja 1.12+).
 */
const fs = require('fs');
const path = require('path');
const {
  createRunOncePlugin,
  withDangerousMod,
  withSettingsGradle,
} = require('expo/config-plugins');

const GRADLE_FILE = 'cmake-windows-fix.gradle';
const APPLY_LINE = 'apply from: new File(settingsDir, "cmake-windows-fix.gradle")';

const GRADLE_CONTENTS = `// Generated by plugins/with-android-cmake-windows-fix.js
// Applied from settings.gradle so CMake version is set before AGP locks it.

def isWindows = System.getProperty("os.name").toLowerCase().contains("windows")
def cmakeVersionOverride = ""
try {
    cmakeVersionOverride = settings.providers.gradleProperty("android.cmakeVersion").getOrElse("").trim()
} catch (ignored) {
}
if (cmakeVersionOverride.isEmpty() && isWindows) {
    cmakeVersionOverride = "3.31.6"
}

if (!cmakeVersionOverride.isEmpty() && isWindows) {
    def sdkDir = System.getenv("ANDROID_HOME") ?: System.getenv("ANDROID_SDK_ROOT")
    if (sdkDir) {
        def cmakeBin = new File(sdkDir, "cmake/\${cmakeVersionOverride}/bin/cmake.exe")
        if (!cmakeBin.exists()) {
            throw new GradleException(
                "Windows Android builds need CMake \${cmakeVersionOverride} (Ninja 1.12+) to avoid " +
                "long-path Ninja failures. Install it from Android Studio → SDK Tools " +
                "→ CMake (Show Package Details) → \${cmakeVersionOverride}, or unzip " +
                "https://dl.google.com/android/repository/cmake-\${cmakeVersionOverride}-windows.zip " +
                "into %ANDROID_HOME%/cmake/\${cmakeVersionOverride}/. Looked for: \${cmakeBin}"
            )
        }
    }
    println "[camera-signs] Overriding CMake version: \${cmakeVersionOverride}"
}

def versionToApply = cmakeVersionOverride
gradle.beforeProject { project ->
    def applyCmakeFix = {
        // finalizeDsl runs after the module's android {} block, so it wins over
        // react-native-worklets / reanimated pinning cmake.version to 3.22.1.
        project.androidComponents.finalizeDsl { dsl ->
            if (!versionToApply.isEmpty()) {
                dsl.externalNativeBuild.cmake.version = versionToApply
            }
            def args = dsl.defaultConfig.externalNativeBuild.cmake.arguments
            if (args != null) {
                args.add("-DCMAKE_OBJECT_PATH_MAX=1024")
            }
        }
    }
    project.pluginManager.withPlugin("com.android.application") { applyCmakeFix() }
    project.pluginManager.withPlugin("com.android.library") { applyCmakeFix() }
}
`;

function withAndroidCmakeWindowsFix(config) {
  config = withDangerousMod(config, [
    'android',
    async (config) => {
      const dest = path.join(config.modRequest.platformProjectRoot, GRADLE_FILE);
      fs.writeFileSync(dest, GRADLE_CONTENTS);
      require('../scripts/fix-windows-cmake.js')(config.modRequest.platformProjectRoot);
      return config;
    },
  ]);

  config = withSettingsGradle(config, (config) => {
    if (!config.modResults.contents.includes(GRADLE_FILE)) {
      config.modResults.contents =
        `${config.modResults.contents.trimEnd()}\n\n${APPLY_LINE}\n`;
    }
    return config;
  });

  return config;
}

module.exports = createRunOncePlugin(
  withAndroidCmakeWindowsFix,
  'with-android-cmake-windows-fix',
  '1.0.0',
);
